"""
export_results_csv.py
---------------------
Reads DRA evaluation JSON files and writes a consolidated CSV with one row
per agent pass (both completed and failed). Useful for cross-run analysis,
failure triage, and cost reporting without opening individual JSON files.

Filtering
---------
All passes are included by default. Use --completed-only to restrict to
passes where completed=true and forced_stop=false (same as
export_completed_runs.py).  Dry-run tasks (config.dry_run=true) are always
excluded.

Output columns
--------------
  task_id               Unique task identifier
  sme_name              SME who authored the prompt
  domain                MC/IB domain
  research_type         CRP | RCP | SCP | LDP | FSP
  iat_type              IAT-1 | IAT-2 | IAT-3
  file_count            Number of corpus files
  output_formats        Required output formats (semicolon-separated)
  agent                 claude | openai | gemini | perplexity
  model                 Exact model string
  status                PASS | FAIL
  failure_category      Populated for FAIL rows: error class + message
  input_tokens          Tokens sent to the model
  output_tokens         Tokens generated by the model
  cost_usd              Monetary cost of this pass
  duration_min          Wall-clock time in minutes (2 d.p.)
  response_length_chars Length of response_text in characters
  citations_count       Number of citations returned
  iterations            Agent loop iterations (Claude only; 0 for others)
  dispatched_at         ISO timestamp when the task was dispatched
  completed_at          ISO timestamp when this pass finished
  prompt_id             SME intake form prompt ID (from sme_metadata)
  allocation_id         Allocation ID (from sme_metadata)
  drive_url             GDrive corpus folder URL (from sme_metadata)

Usage
-----
  # Single file
  python export_results_csv.py --input results/task_001.json

  # Single file, custom output path
  python export_results_csv.py --input results/task_001.json \\
      --output ./reports/run_summary.csv

  # Batch: all *.json in a folder
  python export_results_csv.py --input-dir ./results/tasks \\
      --output-dir ./reports

  # Batch, completed passes only
  python export_results_csv.py --input-dir ./results/tasks \\
      --output-dir ./reports --completed-only

  # Dry run: show what would be written without creating files
  python export_results_csv.py --input-dir ./results/tasks --dry-run

Options
-------
  --input FILE          Single input JSON file
  --input-dir DIR       Batch mode: process all *.json files in this folder
  --output FILE         Output CSV path for single-file mode
                        (default: <stem>_results.csv next to input)
  --output-dir DIR      Output folder for batch mode
                        (default: ./exported_csv next to input-dir)
  --completed-only      Include only completed, non-force-stopped passes
  --dry-run             Show what would be written without creating any files
  --summary             Print a summary table after processing (auto in batch)
"""

import argparse
import csv
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path


# ── Constants ─────────────────────────────────────────────────────────────────

DEFAULT_OUTPUT_DIR = "./exported_csv"

CSV_COLUMNS = [
    "task_id",
    "sme_name",
    "domain",
    "research_type",
    "iat_type",
    "file_count",
    "output_formats",
    "agent",
    "model",
    "status",
    "failure_category",
    "input_tokens",
    "output_tokens",
    "cost_usd",
    "duration_min",
    "response_length_chars",
    "citations_count",
    "iterations",
    "dispatched_at",
    "completed_at",
    "prompt_id",
    "allocation_id",
    "drive_url",
    # Content columns — placed last so metadata columns stay readable in narrow views
    "output_files",
    "citations",
    "response_text",
]


# ── Failure categorisation ────────────────────────────────────────────────────

def categorise_failure(pass_data: dict) -> str:
    """
    Return a short, human-readable failure category for a failed pass.
    Returns an empty string for completed passes.
    """
    if pass_data.get("completed"):
        return ""

    error = (pass_data.get("error") or "").strip()
    forced = pass_data.get("forced_stop", False)

    if not error and not forced:
        return "Failed — no error message"

    low = error.lower()

    if "stuck" in low or "in_progress" in low or "aborting" in low:
        return f"Timeout — interaction stuck"
    if "file generation failed" in low:
        # Extract the format list from the error string if present
        m = re.search(r"file generation failed for:\s*(\[.*?\])", error, re.IGNORECASE)
        fmts = m.group(1) if m else ""
        return f"File generation failed {fmts}".strip()
    if "preflight" in low or "max_inline_chars" in low or "3m char" in low:
        return "Pre-flight failed — corpus too large"
    if "budget" in low or "max_cost" in low:
        return "Forced stop — cost budget exceeded"
    if "max_iterations" in low or "iteration" in low and forced:
        return "Forced stop — iteration limit"
    if forced:
        return f"Forced stop — {error[:80]}" if error else "Forced stop"
    if error:
        return error[:120]
    return "Failed — unknown reason"



# ── Content formatters ────────────────────────────────────────────────────────

def _format_output_files(pass_data: dict) -> str:
    """
    Return a semicolon-separated list of output file paths/names.
    Handles both list-of-strings and list-of-dicts shapes seen across adapters.
    """
    raw = pass_data.get("output_files") or []
    if not raw:
        # Fallback: single path field used by some adapter versions
        single = pass_data.get("output_file_path") or ""
        return single.strip()
    parts = []
    for item in raw:
        if isinstance(item, str):
            parts.append(item.strip())
        elif isinstance(item, dict):
            # {path: ..., filename: ..., format: ...} — take whichever is present
            p = item.get("path") or item.get("filename") or item.get("name") or str(item)
            parts.append(str(p).strip())
    return "; ".join(p for p in parts if p)


def _format_citations(pass_data: dict) -> str:
    """
    Format citations as a human-readable comma-separated key=value string.

    Each citation is rendered as:
        title=<title>, url=<url>, snippet=<snippet>

    Multiple citations are separated by " | ".
    Missing fields are omitted. Returns empty string if no citations.

    Example:
        title=IMF WEO, url=https://imf.org/weo | title=World Bank, url=https://worldbank.org
    """
    raw = pass_data.get("citations") or []
    if not raw:
        return ""
    parts = []
    for c in raw:
        pairs = []
        if c.get("title"):
            pairs.append(f"title={c['title']}")
        if c.get("url"):
            pairs.append(f"url={c['url']}")
        if c.get("snippet"):
            snippet = " ".join(c["snippet"].split())
            pairs.append(f"snippet={snippet}")
        if pairs:
            parts.append(", ".join(pairs))
    return " | ".join(parts)


# ── Row builder ───────────────────────────────────────────────────────────────

def build_row(task: dict, pass_data: dict) -> dict:
    """Build one CSV row dict from a task envelope and a single agent pass."""
    pkg  = task.get("package")  or {}
    sme  = task.get("sme_metadata") or {}

    out_fmts = pkg.get("output_formats") or []
    status   = "PASS" if pass_data.get("completed") and not pass_data.get("forced_stop") else "FAIL"

    dur_sec = pass_data.get("total_duration_sec") or 0.0
    dur_min = round(dur_sec / 60, 2)

    return {
        "task_id":               task.get("task_id", ""),
        "sme_name":              sme.get("sme_name", ""),
        "domain":                pkg.get("domain", ""),
        "research_type":         pkg.get("research_type", ""),
        "iat_type":              pkg.get("iat_type", ""),
        "file_count":            pkg.get("file_count", ""),
        "output_formats":        "; ".join(out_fmts) if out_fmts else "none",
        "agent":                 pass_data.get("agent", ""),
        "model":                 pass_data.get("model", ""),
        "status":                status,
        "failure_category":      categorise_failure(pass_data),
        "input_tokens":          pass_data.get("input_tokens", ""),
        "output_tokens":         pass_data.get("output_tokens", ""),
        "cost_usd":              pass_data.get("total_cost_usd", ""),
        "duration_min":          dur_min,
        "response_length_chars": pass_data.get("response_length") or len(pass_data.get("response_text") or ""),
        "citations_count":       pass_data.get("citations_count", ""),
        "iterations":            pass_data.get("iterations", ""),
        "dispatched_at":         task.get("dispatched_at", ""),
        "completed_at":          pass_data.get("completed_at", ""),
        "prompt_id":             sme.get("prompt_id", ""),
        "allocation_id":         sme.get("allocation_id", ""),
        "drive_url":             sme.get("drive_url", ""),
        # Content columns
        "output_files":          _format_output_files(pass_data),
        "citations":        _format_citations(pass_data),
        "response_text":         (pass_data.get("response_text") or "").strip(),
    }


# ── Filtering ─────────────────────────────────────────────────────────────────

def extract_passes(task: dict, completed_only: bool) -> list[dict]:
    """
    Return all agent pass dicts for this task, subject to filtering rules.
    Dry-run tasks are always excluded entirely.
    """
    if (task.get("config") or {}).get("dry_run", False):
        return []

    passes = []
    for _agent, agent_passes in (task.get("agent_results") or {}).items():
        for p in agent_passes:
            if completed_only:
                if p.get("completed") is True and p.get("forced_stop") is False:
                    passes.append(p)
            else:
                passes.append(p)
    return passes


# ── File processing ───────────────────────────────────────────────────────────

def normalise_to_list(data) -> list[dict]:
    if isinstance(data, dict):
        return [data]
    elif isinstance(data, list):
        return data
    return []


def process_file(
    input_path: Path,
    completed_only: bool,
) -> list[dict]:
    """
    Parse one JSON file and return a list of CSV row dicts.
    Returns an empty list on read errors.
    """
    try:
        with open(input_path, encoding="utf-8") as f:
            data = json.load(f)
    except (json.JSONDecodeError, OSError) as e:
        print(f"  [ERROR] Cannot read {input_path}: {e}", file=sys.stderr)
        return []

    rows = []
    for task in normalise_to_list(data):
        for pass_data in extract_passes(task, completed_only):
            rows.append(build_row(task, pass_data))

    # Sort rows by dispatched_at so the CSV is chronological within a file
    rows.sort(key=lambda r: r.get("dispatched_at") or "")
    return rows


def write_csv(rows: list[dict], output_path: Path) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=CSV_COLUMNS)
        writer.writeheader()
        writer.writerows(rows)


# ── Output path helpers ───────────────────────────────────────────────────────

def default_single_output(input_path: Path) -> Path:
    return input_path.parent / f"{input_path.stem}_results.csv"


def default_batch_output(input_dir: Path) -> Path:
    return input_dir.parent / DEFAULT_OUTPUT_DIR.lstrip("./")


# ── Main ──────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(
        description=(
            "Export DRA evaluation JSON results to a consolidated CSV. "
            "One row per agent pass (all passes by default; use "
            "--completed-only to restrict to successes)."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )

    input_group = parser.add_mutually_exclusive_group(required=True)
    input_group.add_argument("--input",     metavar="FILE", help="Single input JSON file")
    input_group.add_argument("--input-dir", metavar="DIR",  help="Batch: folder of JSON files")

    parser.add_argument(
        "--output", metavar="FILE",
        help="Output CSV path for single-file mode (default: <stem>_results.csv next to input)",
    )
    parser.add_argument(
        "--output-dir", metavar="DIR",
        help=f"Output folder for batch mode (default: {DEFAULT_OUTPUT_DIR} next to input-dir)",
    )
    parser.add_argument(
        "--completed-only", action="store_true",
        help="Include only completed, non-force-stopped passes (mirrors export_completed_runs.py)",
    )
    parser.add_argument(
        "--dry-run", action="store_true",
        help="Show what would be written without creating any files",
    )
    parser.add_argument(
        "--summary", action="store_true",
        help="Print a summary table after processing (auto-enabled in batch mode)",
    )

    args = parser.parse_args()

    if args.output and args.input_dir:
        parser.error("--output can only be used with --input, not --input-dir")

    # ── Collect input files ───────────────────────────────────────────────────
    if args.input:
        input_files = [Path(args.input)]
    else:
        input_dir = Path(args.input_dir)
        if not input_dir.exists():
            print(f"[ERROR] Input dir not found: {input_dir}", file=sys.stderr)
            sys.exit(1)
        input_files = sorted(input_dir.glob("*.json"))
        if not input_files:
            print(f"[WARN] No *.json files found in {input_dir}", file=sys.stderr)
            sys.exit(0)

    # ── Resolve output path(s) ────────────────────────────────────────────────
    batch_mode = bool(args.input_dir)

    if batch_mode:
        out_dir  = Path(args.output_dir) if args.output_dir else default_batch_output(Path(args.input_dir))
        out_path = out_dir / "results_consolidated.csv"
    else:
        out_path = Path(args.output) if args.output else default_single_output(input_files[0])

    print(f"\n-- DRA Results CSV Exporter --")
    print(f"  Mode           : {'batch' if batch_mode else 'single file'}")
    print(f"  Files          : {len(input_files)}")
    print(f"  Completed only : {args.completed_only}")
    print(f"  Output         : {out_path}")
    print(f"  Dry run        : {args.dry_run}")
    print()

    # ── Process ───────────────────────────────────────────────────────────────
    all_rows: list[dict] = []
    file_stats: list[dict] = []

    for in_path in input_files:
        rows = process_file(in_path, args.completed_only)
        n_pass = sum(1 for r in rows if r["status"] == "PASS")
        n_fail = sum(1 for r in rows if r["status"] == "FAIL")
        all_rows.extend(rows)
        file_stats.append({"file": in_path.name, "rows": len(rows), "pass": n_pass, "fail": n_fail})

        status_str = f"pass={n_pass}  fail={n_fail}  total={len(rows)}"
        if not rows:
            print(f"  [SKIP]     {in_path.name}  (no qualifying passes)")
        else:
            print(f"  [OK]       {in_path.name}  {status_str}")

    # Re-sort consolidated rows chronologically across files
    all_rows.sort(key=lambda r: r.get("dispatched_at") or "")

    # ── Write ─────────────────────────────────────────────────────────────────
    if not args.dry_run and all_rows:
        write_csv(all_rows, out_path)
        print(f"\n  Written: {out_path}  ({len(all_rows)} rows)")
    elif args.dry_run:
        print(f"\n  [Dry run] Would write {len(all_rows)} rows to: {out_path}")
    else:
        print("\n  [WARN] No rows to write — CSV not created.")

    # ── Summary ───────────────────────────────────────────────────────────────
    if args.summary or batch_mode:
        total_pass = sum(1 for r in all_rows if r["status"] == "PASS")
        total_fail = sum(1 for r in all_rows if r["status"] == "FAIL")
        total_cost = sum(
            float(r["cost_usd"]) for r in all_rows
            if r["cost_usd"] not in ("", None)
        )

        print(f"\n-- Summary --")
        print(f"  Input files    : {len(input_files)}")
        print(f"  Total rows     : {len(all_rows)}")
        print(f"  PASS           : {total_pass}")
        print(f"  FAIL           : {total_fail}")
        print(f"  Pass rate      : {total_pass / len(all_rows) * 100:.1f}%" if all_rows else "  Pass rate      : n/a")
        print(f"  Total cost     : ${total_cost:,.4f}")

        if total_fail:
            fail_cats: dict[str, int] = {}
            for r in all_rows:
                if r["status"] == "FAIL":
                    cat = r["failure_category"] or "Unknown"
                    fail_cats[cat] = fail_cats.get(cat, 0) + 1
            print(f"\n  Failure breakdown:")
            for cat, count in sorted(fail_cats.items(), key=lambda x: -x[1]):
                print(f"    {count}x  {cat}")

        by_rt: dict[str, dict] = {}
        for r in all_rows:
            rt = r["research_type"] or "Unknown"
            if rt not in by_rt:
                by_rt[rt] = {"pass": 0, "total": 0}
            by_rt[rt]["total"] += 1
            if r["status"] == "PASS":
                by_rt[rt]["pass"] += 1
        if by_rt:
            print(f"\n  Pass rate by research type:")
            for rt, counts in sorted(by_rt.items()):
                pct = counts["pass"] / counts["total"] * 100
                print(f"    {rt:<8} {counts['pass']}/{counts['total']}  ({pct:.0f}%)")

        if not args.dry_run and all_rows:
            print(f"\n  Output: {out_path}")

    print()


if __name__ == "__main__":
    main()