def replace_with_blocks(text, file_name):
    if not isinstance(text, str) or not text.strip(): return text, 0
    if text in TEXT_CACHE: return TEXT_CACHE[text]

    with GPU_LOCK:
        res_std = analyzer_standard.analyze(text=text, entities=ENTITIES_STANDARD, language='en', score_threshold=0.8)
        res_trf = analyzer_transformer.analyze(text=text, entities=ENTITIES_TRANSFORMER, language='en', score_threshold=0.8)

    combined_results = res_std + res_trf
    if not combined_results:
        TEXT_CACHE[text] = (text, 0)
        return text, 0

    combined_results.sort(key=lambda x: x.start, reverse=True)
    new_text = text
    count = 0
    for res in combined_results:
        match_str = text[res.start:res.end].strip()
        if match_str.lower() not in SAFE_LIST and len(match_str) > 3:
            if file_name not in AUDIT_LOG: AUDIT_LOG[file_name] = set()
            AUDIT_LOG[file_name].add(match_str)
            length = res.end - res.start
            new_text = new_text[:res.start] + ("█" * length) + new_text[res.end:]
            count += 1

    TEXT_CACHE[text] = (new_text, count)
    return new_text, count

def redact_pdf(input_path, output_path, file_name):
    doc = pymupdf.open(input_path)
    total_yield = 0

    for page in doc:
        page_height, page_width = page.rect.height, page.rect.width
        text = page.get_text()
        textpage = None
        if len(text.strip()) < 50:
            try:
                textpage = page.get_textpage_ocr(flags=0, language='eng', dpi=150)
                text = page.get_text(textpage=textpage)
            except Exception: pass

        for img in page.get_image_info():
            if img.get("bbox") and pymupdf.Rect(img["bbox"]).y0 < (page_height * 0.08) and pymupdf.Rect(img["bbox"]).width < (page_width * 0.5):
                page.add_redact_annot(pymupdf.Rect(img["bbox"]), fill=(0, 0, 0))
                total_yield += 1

        for drawing in page.get_drawings():
            draw_rect = drawing.get("rect")
            if draw_rect and draw_rect.y0 < (page_height * 0.08) and draw_rect.width < (page_width * 0.5) and draw_rect.height < (page_height * 0.3):
                page.add_redact_annot(draw_rect, fill=(0, 0, 0))
                total_yield += 1

        corp_keywords = ['LLC', 'L.L.C', 'Inc', 'Corp', 'Corporation', 'Ltd', 'Company', 'Co.', 'Group', 'Plc', 'Bank']
        blocks = page.get_text("blocks", textpage=textpage) if textpage else page.get_text("blocks")
        for block in blocks:
            x0, y0, x1, y1, block_text, block_no, block_type = block
            if y0 < (page_height * 0.08) and block_type == 0 and pymupdf.Rect(x0, y0, x1, y1).width < (page_width * 0.5):
                if any(k.lower() in block_text.lower() for k in corp_keywords):
                    page.add_redact_annot(pymupdf.Rect(x0, y0, x1, y1), fill=(0, 0, 0))
                    total_yield += 1

        if text.strip():
            clean_text = text.replace('\n', ' ')
            with GPU_LOCK:
                res_std = analyzer_standard.analyze(text=clean_text, entities=ENTITIES_STANDARD, language='en', score_threshold=0.8)
                res_trf = analyzer_transformer.analyze(text=clean_text, entities=ENTITIES_TRANSFORMER, language='en', score_threshold=0.8)

            raw_pii = set([clean_text[res.start:res.end].strip() for res in (res_std + res_trf) if len(clean_text[res.start:res.end].strip()) > 3])
            for match in re.finditer(corporate_regex, clean_text):
                raw_pii.add(match.group().strip())

            pii_strings = {p for p in raw_pii if p.lower() not in SAFE_LIST}

            for pii in pii_strings:
                if not pii: continue
                if file_name not in AUDIT_LOG: AUDIT_LOG[file_name] = set()
                AUDIT_LOG[file_name].add(pii)

                if textpage:
                    ocr_words = page.get_text("words", textpage=textpage)
                    pii_parts = [w.lower() for w in pii.split()]
                    for w in ocr_words:
                        clean_w = "".join(c for c in w[4].lower() if c.isalnum())
                        if clean_w in pii_parts and len(clean_w) > 2:
                            page.add_redact_annot(pymupdf.Rect(w[:4]), fill=(0, 0, 0))
                            total_yield += 1
                else:
                    areas = page.search_for(pii)
                    if areas:
                        for area in areas:
                            page.add_redact_annot(area, fill=(0, 0, 0))
                            total_yield += 1
                    else:
                        for word in pii.split():
                            clean_w = "".join(c for c in word.lower() if c.isalnum())
                            if len(clean_w) > 2 and not clean_w.isdigit():
                                for w_area in page.search_for(word.strip()):
                                    page.add_redact_annot(w_area, fill=(0, 0, 0))
                                    total_yield += 1

        page.apply_redactions(images=pymupdf.PDF_REDACT_IMAGE_PIXELS, graphics=True)

    doc.save(output_path, garbage=4, deflate=True)
    doc.close()
    return total_yield

def redact_excel(input_path, output_path, file_name):
    wb = openpyxl.load_workbook(input_path)
    total_yield = 0
    for sheet_name in wb.sheetnames:
        for row in wb[sheet_name].iter_rows():
            for cell in row:
                if cell.value and isinstance(cell.value, str):
                    new_val, count = replace_with_blocks(cell.value, file_name)
                    cell.value = new_val
                    total_yield += count
    wb.save(output_path)
    return total_yield

def redact_word(input_path, output_path, file_name):
    doc = docx.Document(input_path)
    total_yield = 0
    for para in doc.paragraphs:
        if para.text:
            new_val, count = replace_with_blocks(para.text, file_name)
            para.text = new_val
            total_yield += count
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                if cell.text:
                    new_val, count = replace_with_blocks(cell.text, file_name)
                    cell.text = new_val
                    total_yield += count
    for section in doc.sections:
        for header_para in section.header.paragraphs:
            if header_para.text:
                new_val, count = replace_with_blocks(header_para.text, file_name)
                header_para.text = new_val
                total_yield += count
        for footer_para in section.footer.paragraphs:
            if footer_para.text:
                new_val, count = replace_with_blocks(footer_para.text, file_name)
                footer_para.text = new_val
                total_yield += count
    doc.save(output_path)
    return total_yield

def redact_pptx(input_path, output_path, file_name):
    prs = pptx.Presentation(input_path)
    total_yield = 0
    for slide in prs.slides:
        for shape in slide.shapes:
            if hasattr(shape, "text") and shape.text:
                new_val, count = replace_with_blocks(shape.text, file_name)
                shape.text = new_val
                total_yield += count
    prs.save(output_path)
    return total_yield

def redact_image_native(input_path, output_path, file_name, ext):
    image = Image.open(input_path)
    if image.mode not in ("RGB", "RGBA"): image = image.convert("RGBA")

    # OCR the image to get raw text for AI analysis
