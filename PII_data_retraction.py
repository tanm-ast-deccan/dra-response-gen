def mirror_structure_and_get_files(source_folder_id, dest_folder_id):
    files_to_process = []

    # Paginated Checkpoint Crawling
    existing_names = set()
    page_token = None
    while True:
        existing_query = f"'{dest_folder_id}' in parents and trashed=false"
        existing_results = master_drive_service.files().list(q=existing_query, fields="nextPageToken, files(name)", pageSize=1000, pageToken=page_token, supportsAllDrives=True, includeItemsFromAllDrives=True).execute()
        for f in existing_results.get('files', []): existing_names.add(f['name'])
        page_token = existing_results.get('nextPageToken')
        if not page_token: break
    NESTED_CHECKPOINTS[dest_folder_id] = existing_names

    # Paginated Input Crawling
    page_token = None
    while True:
        query = f"'{source_folder_id}' in parents and trashed=false"
        results = master_drive_service.files().list(q=query, fields="nextPageToken, files(id, name, mimeType)", pageSize=1000, pageToken=page_token, supportsAllDrives=True, includeItemsFromAllDrives=True).execute()
        items = results.get('files', [])

        for item in items:
            if item['mimeType'] == 'application/vnd.google-apps.folder':
                input_sub_id = item['id']
                if input_sub_id not in FOLDER_MAP:
                    print(f"Mapping directory: {item['name']} ...")
                    FOLDER_MAP[input_sub_id] = get_or_create_folder(item['name'], dest_folder_id)
                files_to_process.extend(mirror_structure_and_get_files(input_sub_id, FOLDER_MAP[input_sub_id]))
            else:
                files_to_process.append({'id': item['id'], 'name': item['name'], 'dest_folder_id': dest_folder_id})

        page_token = results.get('nextPageToken')
        if not page_token: break
    return files_to_process

