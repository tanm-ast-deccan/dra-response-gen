    for match in re.finditer(corporate_regex, clean_text):
        raw_pii.add(match.group().strip())

    pii_strings = {p for p in raw_pii if p.lower() not in SAFE_LIST}

    if not pii_strings:
        image.save(output_path)
        return 0

    # Find the visual coordinates of the PII and paint black boxes
    total_yield = 0
    data = pytesseract.image_to_data(image, output_type=pytesseract.Output.DICT)
    draw = ImageDraw.Draw(image)

    for pii in pii_strings:
        if file_name not in AUDIT_LOG: AUDIT_LOG[file_name] = set()
        AUDIT_LOG[file_name].add(pii)

        pii_parts = [w.lower() for w in pii.split()]
        for i in range(len(data['text'])):
            word = data['text'][i].strip()
            clean_w = "".join(c for c in word.lower() if c.isalnum())
            if len(clean_w) > 2 and clean_w in pii_parts:
                x, y, w, h = data['left'][i], data['top'][i], data['width'][i], data['height'][i]
                draw.rectangle([x, y, x + w, y + h], fill="black")
                total_yield += 1

    image.save(output_path)
    return total_yield

