    if len(raw_text.strip()) < 3:
        image.save(output_path)
        return 0

    # Feed text to AI engines
    clean_text = raw_text.replace('\n', ' ')
    with GPU_LOCK:
        res_std = analyzer_standard.analyze(text=clean_text, entities=ENTITIES_STANDARD, language='en', score_threshold=0.8)
